"""Deduplicate frozen Phase 2 annotation issues, without declaring them gold labels."""
from collections import Counter

CATEGORIES = ('benign_expected', 'requires_lexical_sense_review',
              'requires_grammar_boundary_review', 'true_unresolved')


def classify(issue, record, vocab, grammar_ids):
    annotations = [a for a in record['annotations'] if a['start'] == issue['start']]
    a = next((a for a in annotations if a.get('vocab_id') == issue.get('candidate_id')), None)
    if a is None:
        return 'true_unresolved', 'annotation_not_found'
    if record['text_ko'][a['start']:a['end']] != a['surface']:
        return 'true_unresolved', 'surface_span_mismatch'
    if any(i < 0 or i >= len(record['raw_morphology']) for i in a['morph_indices']):
        return 'true_unresolved', 'invalid_morph_indices'
    morphs = [record['raw_morphology'][i] for i in a['morph_indices']]
    signature = '+'.join(m['tag'] for m in morphs)
    entry = vocab.get(a.get('vocab_id'))
    if entry and any(a.get(k) != entry[k] for k in ('lemma', 'pos', 'sense')):
        return 'true_unresolved', 'db_disagreement'
    kind = issue['type']
    if kind in ('Kiwi_POS_sense_disagreement', 'sense_extension_review', 'restricted_sense_context_review'):
        return 'requires_lexical_sense_review', kind + ':' + str(a.get('sense'))
    if kind == 'sense_disambiguation':
        lemma, pos = a['lemma'], a['pos']
        candidates = [e for e in vocab.values() if e['lemma'] == lemma and e['pos'] == pos]
        pos_tag = {'pronoun': 'NP', 'determiner': 'MM', 'noun': 'NNG',
                   'verb': 'VV', 'adjective': 'VA', 'counter': 'NNB'}.get(pos)
        # NP vs MM resolves 저 structurally. Same-POS homonyms (눈/일 etc.)
        # remain sense reviews; defaults in the generated annotation are not proof.
        if len(candidates) == 1 and len(morphs) == 1 and morphs[0]['tag'] == pos_tag:
            return 'benign_expected', 'unique_pos:' + signature
        return 'requires_lexical_sense_review', 'same_pos_or_context_needed:' + signature
    if kind == 'compound_grouping':
        if entry and signature in ('NNG+XSV', 'NNG+XSA', 'NNG+XSN'):
            return 'benign_expected', 'registered_compound:' + signature
        return 'requires_grammar_boundary_review', 'compound_pattern:' + signature
    if kind == 'bound_noun_or_counter':
        # A reviewable shared numeric pattern, NOT blanket approval of all NNB.
        index = a['morph_indices'][0]
        preceding = record['raw_morphology'][index - 1] if index else {}
        numeric = preceding.get('tag') in ('NR', 'SN') or (
            preceding.get('tag') == 'MM' and preceding.get('form') in ('한', '두', '세', '네', '몇'))
        if entry and entry['pos'] == 'counter' and signature == 'NNB' and numeric:
            return 'benign_expected', 'registered_numeric_counter'
        return 'requires_grammar_boundary_review', 'counter_context:' + signature
    if kind in ('grammar_content_boundary', 'attributive_pos_boundary'):
        # Keep template QA queued: a grammar ID generated by the same analyzer
        # is not independent proof of the complete licensed construction.
        if kind == 'grammar_content_boundary' and a.get('grammar_id') not in grammar_ids:
            return 'true_unresolved', 'unlicensed_grammar'
        return 'requires_grammar_boundary_review', str(a.get('grammar_id') or a.get('lemma'))
    return 'true_unresolved', 'unhandled_issue_type:' + kind


def triage(records, vocab, grammar_ids):
    groups = {}
    counts = Counter({c: 0 for c in CATEGORIES})
    for record in records:
        for issue in record['annotation_review_required']:
            category, pattern = classify(issue, record, vocab, grammar_ids)
            key = (category, issue['type'], issue.get('candidate_id'), pattern)
            group = groups.setdefault(key, {'category': category, 'type': issue['type'],
                'vocab_id': issue.get('candidate_id'), 'lemma': issue.get('lemma'),
                'pattern': pattern, 'occurrences': [], 'review_status': 'template_review_pending'
                if category != 'true_unresolved' else 'individual_review_required'})
            start = issue['start']
            group['occurrences'].append({'text': record['text_number'], 'start': start,
                                        'surface': issue['surface']})
            group.setdefault('representative_context', record['text_ko'][max(0, start - 25):start + 40])
            counts[category] += 1
    return {'status': 'triaged_not_human_approved', 'occurrence_counts': dict(counts),
            'group_counts': dict(Counter(g['category'] for g in groups.values())),
            'total_occurrences': sum(counts.values()), 'total_groups': len(groups),
            'groups': list(groups.values()),
            'cache_policy': 'After one human template approval, reuse only matching ID, sense, '
                            'morphological signature and context preconditions; invalidate on '
                            'vocab/grammar/analyzer/rule version change. Never reuse a sense default as proof.'}
